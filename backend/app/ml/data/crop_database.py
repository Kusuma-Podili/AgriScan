from typing import Dict, List, Optional, Any
from pydantic import BaseModel, Field


class CropKcStages(BaseModel):
    initial: float = Field(..., description="Crop coefficient Kc for initial growth stage")
    mid: float = Field(..., description="Crop coefficient Kc for mid-season peak vegetative/reproductive stage")
    end: float = Field(..., description="Crop coefficient Kc for late season maturity/harvest stage")


class NutrientUptakeRate(BaseModel):
    n_kg_per_ton: float = Field(..., description="Nitrogen removal per metric ton of economic yield (kg/t)")
    p2o5_kg_per_ton: float = Field(..., description="Phosphorus (P2O5) removal per metric ton (kg/t)")
    k2o_kg_per_ton: float = Field(..., description="Potassium (K2O) removal per metric ton (kg/t)")
    s_kg_per_ton: float = Field(0.0, description="Sulphur removal per metric ton (kg/t)")
    zn_g_per_ton: float = Field(0.0, description="Zinc removal per metric ton (g/t)")
    fe_g_per_ton: float = Field(0.0, description="Iron removal per metric ton (g/t)")


class CropAgronomicProfile(BaseModel):
    id: str
    name: str
    scientific_name: str
    family: str
    category: str  # Cereals, Pulses, Oilseeds, Commercial, Spices, Vegetables, Fruits, Plantation, Fodder, Fiber
    climatic_zone: str

    # Temperature Boundaries (°C)
    temp_min_c: float
    temp_opt_min_c: float
    temp_opt_max_c: float
    temp_max_c: float

    # Precipitation / Water Requirements (mm/growing cycle)
    rainfall_min_mm: float
    rainfall_opt_min_mm: float
    rainfall_opt_max_mm: float
    rainfall_max_mm: float

    # Soil Reaction Boundaries (pH)
    ph_min: float
    ph_opt_min: float
    ph_opt_max: float
    ph_max: float

    # Edaphic / Salinity
    salinity_tolerance_ds_m: float  # Electrical conductivity ECe threshold
    drainage_preference: List[str]
    suitable_soil_textures: List[str]

    # Phenology & Growing Degree Days (GDD)
    growing_period_days_min: int
    growing_period_days_max: int
    base_temperature_c: float  # T_base for GDD computation
    kc_stages: CropKcStages

    # Nutrition & Yield
    nutrient_uptake: NutrientUptakeRate
    benchmark_yield_ton_ha: float
    typical_water_req_mm: float

    # Economics & Risk (Standardized Global / Regional Averages in USD)
    cost_of_cultivation_usd_ha: float
    market_price_usd_per_ton: float
    risk_volatility_index: float  # 0.0 (low risk) to 1.0 (very high volatility)

    # Biological Vulnerabilities
    primary_pests: List[str]
    primary_diseases: List[str]

    # Agronomic Guidance
    agronomic_advisory: str



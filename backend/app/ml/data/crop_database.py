def get_crop_by_id(crop_id: str) -> Optional[CropAgronomicProfile]:
    """Retrieve full agronomic crop profile by unique slug identifier."""
    return CROP_DATABASE.get(crop_id.lower().strip())


def list_all_crops() -> List[CropAgronomicProfile]:
    """Return all available agronomic crop profiles."""
    return list(CROP_DATABASE.values())


def filter_crops_by_category(category: str) -> List[CropAgronomicProfile]:
    """Filter crops by agricultural classification category."""
    return [c for c in CROP_DATABASE.values() if c.category.lower() == category.lower().strip()]


def get_crop_names() -> List[str]:
    """Return sorted list of crop names."""
    return sorted([c.name for c in CROP_DATABASE.values()])
